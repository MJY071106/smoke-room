export function scoreGrade(total: number): { label: string; description: string } {
  if (total >= 90)
    return {
      label: '敏锐的实验者',
      description: '你几乎每次都直接抓住了那个被悄悄改动的变量。',
    }
  if (total >= 70)
    return {
      label: '稳健的求证者',
      description: '偶有迟疑，但你用解析把每一个坑都填上了。',
    }
  if (total >= 50)
    return {
      label: '认真的观察者',
      description: '几个竞争解释曾经说服过你——它们确实都长得很像答案。',
    }
  return {
    label: '继续探索的学徒',
    description: '值得回看那些"看起来也对"的选项，它们的解析里藏着本章的要点。',
  }
}
